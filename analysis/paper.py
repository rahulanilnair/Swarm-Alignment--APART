"""Every number, table and figure the paper quotes, recomputed from result files.

    uv run python paper.py --e1 ../results/e1_fixtures --e2 ../results/e2_live \
        --e0 ../results/e0_rahul --manuscript ../manuscript

Writes manuscript/numbers.tex (LaTeX macros), manuscript/tables/{e1_main,e1_groups,
live}.tex and manuscript/figures/e1_groups.pdf. Thresholds come from analyze.py's
calibration rule (frozen on calibration negatives at --fpr-target), applied to
held-out episodes. Nothing here reads model outputs other than predictions.csv.
"""
